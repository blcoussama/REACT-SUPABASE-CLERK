-- =============================================================================
-- Job portal schema + Row Level Security (Clerk "third-party auth" for Supabase)
--
-- Identity comes from the Clerk session token verified by Supabase:
--   auth.jwt() ->> 'sub'        Clerk user id (e.g. "user_2abc...")
--   auth.jwt() ->> 'user_role'  "candidate" | "recruiter", copied from the Clerk
--                               *public* metadata (only writable server-side, see
--                               supabase/functions/set-role) through the session
--                               token customisation {"user_role": "{{user.public_metadata.role}}"}
--
-- Every table has RLS enabled; nothing is reachable with the anon key alone.
-- =============================================================================

-- ---------------------------------------------------------------- tables -----

create table if not exists public.companies (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    name        text not null check (char_length(name) between 1 and 100),
    logo_url    text not null,
    created_by  text not null default (auth.jwt() ->> 'sub')
);

create table if not exists public.jobs (
    id            bigint generated by default as identity primary key,
    created_at    timestamptz not null default now(),
    recruiter_id  text not null default (auth.jwt() ->> 'sub'),
    title         text not null check (char_length(title) between 1 and 200),
    description   text not null check (char_length(description) <= 10000),
    location      text not null,
    company_id    bigint not null references public.companies (id) on delete restrict,
    requirements  text not null check (char_length(requirements) <= 20000),
    "isOpen"      boolean not null default true
);

create table if not exists public.applications (
    id            bigint generated by default as identity primary key,
    created_at    timestamptz not null default now(),
    job_id        bigint not null references public.jobs (id) on delete cascade,
    candidate_id  text not null default (auth.jwt() ->> 'sub'),
    name          text,
    status        text not null default 'applied'
                  check (status in ('applied', 'interviewing', 'hired', 'rejected')),
    resume        text not null,  -- path inside the PRIVATE "resumes" bucket, never a public URL
    skills        text,
    experience    integer check (experience between 0 and 80),
    education     text check (education in ('Intermediate', 'Graduate', 'Post Graduate')),
    unique (job_id, candidate_id)
);

create table if not exists public.saved_jobs (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    user_id     text not null default (auth.jwt() ->> 'sub'),
    job_id      bigint not null references public.jobs (id) on delete cascade,
    unique (user_id, job_id)
);

create index if not exists jobs_recruiter_id_idx on public.jobs (recruiter_id);
create index if not exists jobs_company_id_idx on public.jobs (company_id);
create index if not exists applications_job_id_idx on public.applications (job_id);
create index if not exists applications_candidate_id_idx on public.applications (candidate_id);
create index if not exists saved_jobs_user_id_idx on public.saved_jobs (user_id);

-- ------------------------------------------------------------ privileges -----
-- Least privilege on top of RLS: anon gets nothing, authenticated only what the app needs.

revoke all on public.companies, public.jobs, public.applications, public.saved_jobs from anon, authenticated;

grant select, insert on public.companies to authenticated;
grant select, insert, update, delete on public.jobs to authenticated;
grant select, insert on public.applications to authenticated;
grant update (status) on public.applications to authenticated;  -- a recruiter can only change the status
grant select, insert, delete on public.saved_jobs to authenticated;

-- ------------------------------------------------------------------ RLS ------

alter table public.companies    enable row level security;
alter table public.jobs         enable row level security;
alter table public.applications enable row level security;
alter table public.saved_jobs   enable row level security;

-- companies: readable by every signed-in user, created by recruiters only
drop policy if exists "companies: read" on public.companies;
create policy "companies: read" on public.companies
    for select to authenticated using (true);

drop policy if exists "companies: recruiters create" on public.companies;
create policy "companies: recruiters create" on public.companies
    for insert to authenticated
    with check (
        (select auth.jwt() ->> 'user_role') = 'recruiter'
        and created_by = (select auth.jwt() ->> 'sub')
    );

-- jobs: readable by every signed-in user, written only by the recruiter who owns them
drop policy if exists "jobs: read" on public.jobs;
create policy "jobs: read" on public.jobs
    for select to authenticated using (true);

drop policy if exists "jobs: recruiters create their own" on public.jobs;
create policy "jobs: recruiters create their own" on public.jobs
    for insert to authenticated
    with check (
        (select auth.jwt() ->> 'user_role') = 'recruiter'
        and recruiter_id = (select auth.jwt() ->> 'sub')
    );

drop policy if exists "jobs: owner updates" on public.jobs;
create policy "jobs: owner updates" on public.jobs
    for update to authenticated
    using (recruiter_id = (select auth.jwt() ->> 'sub'))
    with check (recruiter_id = (select auth.jwt() ->> 'sub'));

drop policy if exists "jobs: owner deletes" on public.jobs;
create policy "jobs: owner deletes" on public.jobs
    for delete to authenticated
    using (recruiter_id = (select auth.jwt() ->> 'sub'));

-- applications: visible to the candidate who applied and to the recruiter who owns the job
drop policy if exists "applications: candidate or job owner reads" on public.applications;
create policy "applications: candidate or job owner reads" on public.applications
    for select to authenticated
    using (
        candidate_id = (select auth.jwt() ->> 'sub')
        or exists (
            select 1 from public.jobs j
            where j.id = applications.job_id
              and j.recruiter_id = (select auth.jwt() ->> 'sub')
        )
    );

drop policy if exists "applications: candidates apply to open jobs" on public.applications;
create policy "applications: candidates apply to open jobs" on public.applications
    for insert to authenticated
    with check (
        (select auth.jwt() ->> 'user_role') = 'candidate'
        and candidate_id = (select auth.jwt() ->> 'sub')
        and status = 'applied'
        -- the resume must be stored in the candidate's own folder
        and split_part(resume, '/', 1) = (select auth.jwt() ->> 'sub')
        and exists (select 1 from public.jobs j where j.id = applications.job_id and j."isOpen")
    );

drop policy if exists "applications: job owner updates the status" on public.applications;
create policy "applications: job owner updates the status" on public.applications
    for update to authenticated
    using (
        exists (
            select 1 from public.jobs j
            where j.id = applications.job_id
              and j.recruiter_id = (select auth.jwt() ->> 'sub')
        )
    )
    with check (
        exists (
            select 1 from public.jobs j
            where j.id = applications.job_id
              and j.recruiter_id = (select auth.jwt() ->> 'sub')
        )
    );

-- saved_jobs: strictly personal
drop policy if exists "saved_jobs: owner reads" on public.saved_jobs;
create policy "saved_jobs: owner reads" on public.saved_jobs
    for select to authenticated using (user_id = (select auth.jwt() ->> 'sub'));

drop policy if exists "saved_jobs: owner creates" on public.saved_jobs;
create policy "saved_jobs: owner creates" on public.saved_jobs
    for insert to authenticated with check (user_id = (select auth.jwt() ->> 'sub'));

drop policy if exists "saved_jobs: owner deletes" on public.saved_jobs;
create policy "saved_jobs: owner deletes" on public.saved_jobs
    for delete to authenticated using (user_id = (select auth.jwt() ->> 'sub'));

-- -------------------------------------------------------------- storage ------
-- resumes: PRIVATE bucket, files under "<clerk user id>/...", read through short-lived signed URLs.
-- company-logo: public bucket (logos are public), uploads by recruiters only.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
    ('resumes', 'resumes', false, 5242880, array[
        'application/pdf',
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
    ]),
    ('company-logo', 'company-logo', true, 2097152, array['image/png', 'image/jpeg', 'image/webp'])
on conflict (id) do update
    set public = excluded.public,
        file_size_limit = excluded.file_size_limit,
        allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "resumes: candidates upload to their folder" on storage.objects;
create policy "resumes: candidates upload to their folder" on storage.objects
    for insert to authenticated
    with check (
        bucket_id = 'resumes'
        and (select auth.jwt() ->> 'user_role') = 'candidate'
        and (storage.foldername(name))[1] = (select auth.jwt() ->> 'sub')
    );

drop policy if exists "resumes: candidate or job owner reads" on storage.objects;
create policy "resumes: candidate or job owner reads" on storage.objects
    for select to authenticated
    using (
        bucket_id = 'resumes'
        and (
            (storage.foldername(name))[1] = (select auth.jwt() ->> 'sub')
            or exists (
                select 1
                from public.applications a
                join public.jobs j on j.id = a.job_id
                where a.resume = objects.name
                  and j.recruiter_id = (select auth.jwt() ->> 'sub')
            )
        )
    );

drop policy if exists "resumes: candidates delete their files" on storage.objects;
create policy "resumes: candidates delete their files" on storage.objects
    for delete to authenticated
    using (
        bucket_id = 'resumes'
        and (storage.foldername(name))[1] = (select auth.jwt() ->> 'sub')
    );

drop policy if exists "company-logo: recruiters upload to their folder" on storage.objects;
create policy "company-logo: recruiters upload to their folder" on storage.objects
    for insert to authenticated
    with check (
        bucket_id = 'company-logo'
        and (select auth.jwt() ->> 'user_role') = 'recruiter'
        and (storage.foldername(name))[1] = (select auth.jwt() ->> 'sub')
    );
